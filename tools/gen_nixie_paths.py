#!/usr/bin/env python3
"""Flattens the design's Nixie digit paths (Weather App.dc.html, NIXIE_PATHS)
into polylines and converts the screen saver's oklch colours to sRGB hex.

Output: main/weather_saver_digits.h (digit polylines in tube-local pixels).
The oklch conversion is printed so the values can be pasted into
weather_saver.c when the design changes.

    python3 tools/gen_nixie_paths.py > main/weather_saver_digits.h
"""
import math, re, sys

# Copied from NIXIE_PATHS in the design; y coordinates are scaled by 1.64 there.
PATHS = [
    'M30 4 C54 4 56 96 30 96 C4 96 6 4 30 4 Z',
    'M30 2 L30 98',
    'M9 27 C9 6 22 3 30 3 C42 3 51 11 51 26 C51 48 18 62 9 97 L52 97',
    'M9 4 L51 4 L27 40 C44 38 53 50 53 66 C53 86 42 97 29 97 C18 97 10 90 7 80',
    'M41 98 L41 3 L6 70 L55 70',
    'M50 4 L17 4 L13 45 C19 39 25 37 31 37 C45 37 53 50 53 67 C53 86 42 97 30 97 C18 97 10 89 7 80',
    'M45 4 C27 22 8 46 8 68 C8 86 18 97 30 97 C43 97 52 86 52 70 C52 54 43 44 30 44 C19 44 11 52 9 62',
    'M6 4 L54 4 L20 98',
    'M30 47 C16 47 12 37 12 26 C12 13 20 3 30 3 C40 3 48 13 48 26 C48 37 44 47 30 47 C15 47 8 58 8 71 C8 86 18 97 30 97 C42 97 52 86 52 71 C52 58 45 47 30 47 Z',
    'M52 34 C50 47 41 55 30 55 C17 55 8 46 8 30 C8 14 18 3 30 3 C42 3 52 13 52 30 C52 54 38 78 20 98',
]
Y_STRETCH = 1.64            # design scales y by this before drawing
VIEW_W, VIEW_H = 60, 164    # SVG viewBox
BOX_W, BOX_H = 66, 180      # tube window in px
SCALE = min(BOX_W / VIEW_W, BOX_H / VIEW_H)   # preserveAspectRatio "meet"
OFF_X = (BOX_W - VIEW_W * SCALE) / 2
OFF_Y = (BOX_H - VIEW_H * SCALE) / 2
STEPS = 10

def flatten(d):
    toks = re.findall(r'[MLCZ]|-?\d+(?:\.\d+)?', d)
    pts, i, cur, start = [], 0, (0, 0), (0, 0)
    while i < len(toks):
        t = toks[i]; i += 1
        if t in 'ML':
            cur = (float(toks[i]), float(toks[i + 1])); i += 2
            if t == 'M': start = cur
            pts.append(cur)
        elif t == 'C':
            p = [cur] + [(float(toks[i + 2 * k]), float(toks[i + 2 * k + 1])) for k in range(3)]; i += 6
            for s in range(1, STEPS + 1):
                u = s / STEPS; v = 1 - u
                pts.append((v**3 * p[0][0] + 3 * v * v * u * p[1][0] + 3 * v * u * u * p[2][0] + u**3 * p[3][0],
                            v**3 * p[0][1] + 3 * v * v * u * p[1][1] + 3 * v * u * u * p[2][1] + u**3 * p[3][1]))
            cur = p[3]
        elif t == 'Z':
            pts.append(start)
    return pts

def oklch(l, c, h, a=None):
    hr = math.radians(h)
    a_, b_ = c * math.cos(hr), c * math.sin(hr)
    l_ = (l + 0.3963377774 * a_ + 0.2158037573 * b_) ** 3
    m_ = (l - 0.1055613458 * a_ - 0.0638541728 * b_) ** 3
    s_ = (l - 0.0894841775 * a_ - 1.2914855480 * b_) ** 3
    rgb = (4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
           -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
           -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_)
    def g(x):
        x = min(max(x, 0), 1)
        return 12.92 * x if x <= 0.0031308 else 1.055 * x ** (1 / 2.4) - 0.055
    return '0x%02X%02X%02X' % tuple(round(g(x) * 255) for x in rgb)

if __name__ == '__main__':
    print('/* Generated by tools/gen_nixie_paths.py from the design\'s NIXIE_PATHS -- do not edit. */')
    print('#ifndef WEATHER_SAVER_DIGITS_H\n#define WEATHER_SAVER_DIGITS_H\n')
    print('#include "lvgl.h"\n')
    print('#define SAVER_DIGIT_WINDOW_W %d\n#define SAVER_DIGIT_WINDOW_H %d\n' % (BOX_W, BOX_H))
    for n, d in enumerate(PATHS):
        pts = [(x * SCALE + OFF_X, y * Y_STRETCH * SCALE + OFF_Y) for x, y in flatten(d)]
        print('static const lv_point_precise_t k_saver_digit_%d[] = {' % n)
        print('    ' + ', '.join('{%.1f, %.1f}' % p for p in pts))
        print('};')
    print('\nstatic const struct { const lv_point_precise_t *pts; uint16_t count; } k_saver_digits[10] = {')
    for n, d in enumerate(PATHS):
        print('    { k_saver_digit_%d, (uint16_t)(sizeof k_saver_digit_%d / sizeof k_saver_digit_%d[0]) },' % (n, n, n))
    print('};\n\n#endif')
    sys.stderr.write('oklch(0.19 0.012 50)=%s bar=%s/%s/%s/%s cage=%s/%s cageRing=%s/%s mesh=%s pin1=%s pin2=%s dot=%s/%s/%s\n' % (
        oklch(.19, .012, 50), oklch(.27, .045, 45), oklch(.31, .05, 50), oklch(.25, .04, 42), oklch(.29, .048, 48),
        oklch(.4, .13, 35), oklch(.2, .05, 35), oklch(.32, .01, 60), oklch(.2, .01, 60), oklch(.42, .02, 60),
        oklch(.3, .01, 60), oklch(.26, .01, 60), oklch(.93, .09, 75), oklch(.78, .18, 48), oklch(.66, .21, 38)))
